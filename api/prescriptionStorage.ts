import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto'
import { PRESCRIPTION_MAX_BYTES } from '../src/lib/healthcarePolicy'
import type { EncryptedValue } from './identity'
function key() {
  const encoded = process.env.HEALTHCARE_DOCUMENT_ENCRYPTION_KEY?.trim() ?? ''
  if (!/^[A-Za-z0-9+/]{43}=$/.test(encoded)) throw new Error('Private prescription storage is unavailable.')
  const value = Buffer.from(encoded, 'base64')
  if (value.length !== 32) throw new Error('Private prescription storage is unavailable.')
  return value
}
export function prescriptionStorageReady() { try { key(); return process.env.HEALTHCARE_PRESCRIPTION_ENABLED === 'true' } catch { return false } }
// Accept only a JPEG regenerated by the camera/gallery form. Reject HTML, SVG and MIME spoofing.
export function prescriptionData(data: string) {
  const match = /^data:image\/jpeg;base64,([A-Za-z0-9+/]+={0,2})$/.exec(data)
  if (!match) throw new Error('Choose a JPG or PNG photo using the camera or gallery controls.')
  const bytes = Buffer.from(match[1], 'base64')
  if (bytes.toString('base64') !== match[1] || bytes.length < 1000 || bytes.length > PRESCRIPTION_MAX_BYTES || bytes[0] !== 0xff || bytes[1] !== 0xd8 || bytes[2] !== 0xff || bytes.at(-2) !== 0xff || bytes.at(-1) !== 0xd9) throw new Error('Invalid prescription image; choose a clear photo under 600 KB after processing.')
  return `data:image/jpeg;base64,${bytes.toString('base64')}`
}
export function encryptPrescription(data: string): EncryptedValue {
  const iv = randomBytes(12); const cipher = createCipheriv('aes-256-gcm', key(), iv)
  const ciphertext = Buffer.concat([cipher.update(prescriptionData(data), 'utf8'), cipher.final()])
  return { ciphertext: ciphertext.toString('base64'), iv: iv.toString('hex'), tag: cipher.getAuthTag().toString('hex') }
}
export function decryptPrescription(value: EncryptedValue) {
  const decipher = createDecipheriv('aes-256-gcm', key(), Buffer.from(value.iv, 'hex'))
  decipher.setAuthTag(Buffer.from(value.tag, 'hex'))
  return Buffer.concat([decipher.update(Buffer.from(value.ciphertext, 'base64')), decipher.final()]).toString('utf8')
}
